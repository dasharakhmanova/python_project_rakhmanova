# Составить функцию, которая выведет на экран строку, содержащую
# задаваемое с клавиатуры число символов.
def print_line(k):
    print("*" * k)


k = input("Введите количество символов: ")
while type(k) != int:
    try:
        k = int(k)
    except ValueError:
        print("Неправильно ввели!")
        k = input("Введите количество символов: ")
    else:
        if k < 0:
            print("Число не может быть отрицательным!")
            k = input("Введите количество символов: ")

print_line(k)