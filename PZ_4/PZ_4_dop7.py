# Даны два целых числа A и B (A < B). Вывести в порядке убывания все целые числа между A и B (включая A и B), а также их количество.
a = int(input("Введите A: "))
b = int(input("Введите B: "))
count = 0
for i in range(b, a - 1, -1):  # от B вниз до A включительно
    print(i)
    count += 1
print("Количество чисел:", count)