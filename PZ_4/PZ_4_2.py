#Даны целые положительные числа N и K. Используя только операции сложения и вычитания, найти целое частное от деления нацело N на K, а также остаток от этого деления.
try:
    n = int(input("Введите N: "))
    k = int(input("Введите K: "))
except ValueError:
    print("Неправильно ввели! Нужны целые числа.")
else:
    if n > 0 and k > 0:
        quotient = 0   # частное: сколько раз K поместилось в N
        remainder = n  # остаток: что осталось после вычитаний
        while remainder >= k:
            remainder -= k
            quotient += 1
        print("Частное:", quotient)
        print("Остаток:", remainder)
    else:
        print("Числа должны быть положительными!")