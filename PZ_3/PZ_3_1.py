# Дано четырехзначное число. Проверить истинность высказывания "Данное число читается одинаково слева направо и справа налево".
try:
    n = int(input("Введите четырёхзначное число: "))
except ValueError:
    print("Неправильно ввели! Нужно целое число.")
else:
    if 1000 <= abs(n) <= 9999:
        n = abs(n)
        print(n // 1000 == n % 10 and n // 100 % 10 == n // 10 % 10)
    else:
        print("Число должно быть четырёхзначным!")

