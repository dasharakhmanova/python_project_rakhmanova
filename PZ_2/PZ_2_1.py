#24. С начала суток прошло N секунд (N - целое число). Найти количество полных минут, прошедших с начала суток.

n = input('введите количество секунд ')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("ошибка при вводе")
        n = input("введите количество секунд ")

fullmin = n // 60
print('Количество минут', fullmin)