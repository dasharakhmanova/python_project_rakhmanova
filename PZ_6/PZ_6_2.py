# Дан целочисленный список A размера N. Переписать в новый
# целочисленный список B того же размера вначале все элементы исходного
# списка с четными номерами, а затем — с нечетными:
# A2, A4, A6, …, A1, A3, A5, … . Условный оператор не использовать.
import random

n = input("Введите размер списка N: ")
while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите размер списка N: ")
    else:
        if n < 1:
            print("N должно быть положительным!")
            n = input("Введите размер списка N: ")

a = []
i = 0
while i < n:
    a.append(random.randint(-100, 100))
    i += 1

b = a[1::2] + a[0::2]

print("Список A:", a)
print("Список B:", b)