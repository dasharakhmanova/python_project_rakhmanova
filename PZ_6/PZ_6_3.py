# Дано множество A из N точек (точки заданы своими координатами x, y).
# Найти пару различных точек этого множества с максимальным расстоянием
# между ними и само это расстояние (точки выводятся в том же порядке,
# в котором они перечислены при задании множества A).
# Расстояние R между точками с координатами (x1, y1) и (x2, y2)
# вычисляется по формуле: R = √((x2 – x1)² + (y2 – y1)²).
# Для хранения данных о каждом наборе точек следует использовать по два
# списка: первый список для хранения абсцисс, второй — для хранения
# ординат.
import math


def input_int(text):
    k = input(text)
    while type(k) != int:
        try:
            k = int(k)
        except ValueError:
            print("Неправильно ввели!")
            k = input(text)
    return k


n = input_int("Введите количество точек N: ")
while n < 2:
    print("Точек должно быть не меньше двух!")
    n = input_int("Введите количество точек N: ")

x = []
y = []
i = 1
while i <= n:
    print("Точка", i)
    x.append(input_int("x: "))
    y.append(input_int("y: "))
    i += 1

print("Абсциссы:", x)
print("Ординаты:", y)

max_r = 0
p1 = 0
p2 = 1
i = 0
while i < n - 1:
    j = i + 1
    while j < n:
        r = math.sqrt((x[j] - x[i]) ** 2 + (y[j] - y[i]) ** 2)
        if r > max_r:
            max_r = r
            p1 = i
            p2 = j
        j += 1
    i += 1

print("Первая точка:", (x[p1], y[p1]))
print("Вторая точка:", (x[p2], y[p2]))
print("Расстояние:", max_r)